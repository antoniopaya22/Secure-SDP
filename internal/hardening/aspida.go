// Package hardening implements SecureSDP dynamic hardening.
//
// The controller (Egida master role) derives, for every accepting host, an
// Aspida program from the hardening profiles of the services that host
// exposes, and sends it over the control channel. The accepting host applies
// it through a Hardener: Egida on a real Debian host, or a dry run that only
// renders the program (used in the container lab). An Auditor (Lynis)
// measures the result.
package hardening

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"math"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// Spec is a named set of CIS controls expressed with Egida's Aspida TASKS
// keywords, plus Egida variables (VARS block).
type Spec struct {
	Description string         `yaml:"description" json:"description,omitempty"`
	Sections    []string       `yaml:"sections" json:"sections,omitempty"`
	Points      []string       `yaml:"points" json:"points,omitempty"`
	Controls    []string       `yaml:"controls" json:"controls,omitempty"`
	Exclusions  []string       `yaml:"exclusions" json:"exclusions,omitempty"`
	Tags        []string       `yaml:"tags" json:"tags,omitempty"`
	Vars        map[string]any `yaml:"vars" json:"vars,omitempty"`
}

// Empty reports whether the spec selects no task.
func (s Spec) Empty() bool {
	return len(s.Sections)+len(s.Points)+len(s.Controls)+len(s.Tags) == 0
}

// Merge combines specs: task selections are united, exclusions are united
// (an exclusion from any profile wins, so a service can veto a control that
// would break it) and variables are deep-merged, later specs overriding.
func Merge(specs ...Spec) Spec {
	var out Spec
	for _, s := range specs {
		out.Sections = union(out.Sections, s.Sections)
		out.Points = union(out.Points, s.Points)
		out.Controls = union(out.Controls, s.Controls)
		out.Exclusions = union(out.Exclusions, s.Exclusions)
		out.Tags = union(out.Tags, s.Tags)
		out.Vars = mergeVars(out.Vars, s.Vars)
	}
	// A point that is excluded is not selected explicitly either.
	out.Points = slices.DeleteFunc(out.Points, func(p string) bool { return slices.Contains(out.Exclusions, p) })
	return out
}

func union(a, b []string) []string {
	out := slices.Clone(a)
	for _, v := range b {
		if !slices.Contains(out, v) {
			out = append(out, v)
		}
	}
	sort.Strings(out)
	return out
}

func mergeVars(dst, src map[string]any) map[string]any {
	if len(src) == 0 {
		return dst
	}
	if dst == nil {
		dst = map[string]any{}
	}
	for k, v := range src {
		if sm, ok := v.(map[string]any); ok {
			if dm, ok := dst[k].(map[string]any); ok {
				dst[k] = mergeVars(dm, sm)
				continue
			}
			dst[k] = mergeVars(nil, sm)
			continue
		}
		dst[k] = v
	}
	return dst
}

// Program is the input of RenderAspida.
type Program struct {
	Name        string
	Description string
	Host        string // Egida host group; "localhost" when run on the AH itself
	Spec        Spec
}

// RenderAspida renders an Aspida program (Egida DSL) with connection: local.
// Output is deterministic so it can be hashed and compared.
func RenderAspida(p Program) (string, error) {
	if p.Host == "" {
		p.Host = "localhost"
	}
	if p.Spec.Empty() {
		return "", fmt.Errorf("hardening: profile %q selects no task", p.Name)
	}
	var b strings.Builder
	b.WriteString("# Generated by the SecureSDP controller. Do not edit: it is re-rendered\n")
	b.WriteString("# whenever the services exposed by this accepting host change.\n")
	b.WriteString("MAIN : {\n")
	fmt.Fprintf(&b, "    name: %s;\n", quote(p.Name))
	b.WriteString("    connection: local;\n")
	fmt.Fprintf(&b, "    description: %s;\n", quote(p.Description))
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "HOST : %s;\n\n", quote(p.Host))
	b.WriteString("TASKS : {\n")
	for _, kv := range []struct {
		k string
		v []string
	}{{"sections", p.Spec.Sections}, {"points", p.Spec.Points}, {"controls", p.Spec.Controls}, {"exclusions", p.Spec.Exclusions}, {"tags", p.Spec.Tags}} {
		if len(kv.v) > 0 {
			fmt.Fprintf(&b, "    %s: %s;\n", kv.k, strArray(kv.v))
		}
	}
	b.WriteString("}\n")
	if len(p.Spec.Vars) > 0 {
		b.WriteString("\nVARS : {\n")
		if err := writeVars(&b, p.Spec.Vars, 1); err != nil {
			return "", err
		}
		b.WriteString("}\n")
	}
	return b.String(), nil
}

// Hash returns a short stable digest of a rendered program.
func Hash(aspida string) string {
	sum := sha256.Sum256([]byte(aspida))
	return hex.EncodeToString(sum[:8])
}

func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

func strArray(v []string) string {
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = quote(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func writeVars(b *strings.Builder, vars map[string]any, depth int) error {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	ind := strings.Repeat("    ", depth)
	for _, k := range keys {
		switch v := vars[k].(type) {
		case map[string]any:
			fmt.Fprintf(b, "%s%s: {\n", ind, quote(k))
			if err := writeVars(b, v, depth+1); err != nil {
				return err
			}
			fmt.Fprintf(b, "%s};\n", ind)
		default:
			s, err := value(v)
			if err != nil {
				return fmt.Errorf("hardening: var %q: %w", k, err)
			}
			fmt.Fprintf(b, "%s%s: %s;\n", ind, quote(k), s)
		}
	}
	return nil
}

func value(v any) (string, error) {
	switch x := v.(type) {
	case nil:
		return "null", nil
	case string:
		return quote(x), nil
	case bool:
		return strconv.FormatBool(x), nil
	case int:
		return strconv.Itoa(x), nil
	case int64:
		return strconv.FormatInt(x, 10), nil
	case uint64:
		return strconv.FormatUint(x, 10), nil
	case float64:
		if math.IsNaN(x) || math.IsInf(x, 0) {
			return "", fmt.Errorf("unsupported number %v", x)
		}
		return strconv.FormatFloat(x, 'f', -1, 64), nil
	case []string:
		return strArray(x), nil
	case []any:
		parts := make([]string, len(x))
		for i, e := range x {
			s, err := value(e)
			if err != nil {
				return "", err
			}
			parts[i] = s
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	default:
		return "", fmt.Errorf("unsupported value type %T", v)
	}
}
