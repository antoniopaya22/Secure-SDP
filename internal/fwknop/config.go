// Package fwknop integrates the fwknop Single Packet Authorization
// implementation (https://www.cipherdyne.org/fwknop/): it renders fwknopd
// configuration and per-client access stanzas on accepting hosts, supervises
// the fwknopd daemon, and sends SPA packets from initiating hosts with the
// fwknop client.
package fwknop

import (
	"encoding/base64"
	"fmt"
	"net"
	"regexp"
	"strconv"
	"strings"
	"time"
)

// DefaultSPAPort is the fwknop default UDP port.
const DefaultSPAPort = 62201

// ServerConfig is the subset of fwknopd.conf SecureSDP manages.
type ServerConfig struct {
	Interface  string // interface fwknopd sniffs (the AH public side)
	SPAPort    int
	AccessFile string
	RunDir     string
	// Forwarding enables FORCE_NAT stanzas (forward-mode services).
	Forwarding bool
}

// RenderServerConfig renders fwknopd.conf.
func RenderServerConfig(c ServerConfig) (string, error) {
	if !safeToken(c.Interface) || !safePath(c.AccessFile) || !safePath(c.RunDir) {
		return "", fmt.Errorf("fwknop: unsafe server configuration value")
	}
	if c.SPAPort == 0 {
		c.SPAPort = DefaultSPAPort
	}
	yn := func(b bool) string {
		if b {
			return "Y"
		}
		return "N"
	}
	var b strings.Builder
	b.WriteString("# Generated by sdp-services. Changes are overwritten on restart.\n")
	kv := func(k, v string) { fmt.Fprintf(&b, "%-28s %s;\n", k, v) }
	kv("PCAP_INTF", c.Interface)
	kv("PCAP_FILTER", fmt.Sprintf("udp dst port %d", c.SPAPort))
	kv("ENABLE_PCAP_PROMISC", "N")
	kv("ENABLE_SPA_PACKET_AGING", "Y")
	kv("MAX_SPA_PACKET_AGE", "120")
	kv("ENABLE_DIGEST_PERSISTENCE", "Y")
	kv("ENABLE_IPT_FORWARDING", yn(c.Forwarding))
	kv("ENABLE_IPT_LOCAL_NAT", "N")
	// fwknopd's own SNAT uses fixed --to-ports; the AH adds a plain
	// MASQUERADE rule on its private side instead (see package firewall).
	kv("ENABLE_IPT_SNAT", "N")
	kv("ENABLE_IPT_OUTPUT", "N")
	// Access stanzas change at runtime and fwknopd is reloaded with SIGHUP:
	// keep open SPA windows of other clients across reloads. sdp-services
	// clears the fwknop chains itself before the first start.
	kv("FLUSH_IPT_AT_INIT", "N")
	kv("FLUSH_IPT_AT_EXIT", "Y")
	kv("FWKNOP_RUN_DIR", c.RunDir)
	kv("ACCESS_FILE", c.AccessFile)
	return b.String(), nil
}

// NAT is the FORCE_NAT destination of a forward-mode stanza.
type NAT struct {
	IP   string
	Port int
}

// Stanza is one access.conf entry: the authorization of one client for one
// service, with credentials that only that client knows.
type Stanza struct {
	Comment       string
	OpenPorts     []string // e.g. "tcp/8443"
	KeyBase64     string
	HMACKeyBase64 string
	HMACDigest    string // SHA256 by default
	AccessTimeout time.Duration
	Expires       time.Time
	ForceNAT      *NAT
}

var (
	tokenRE = regexp.MustCompile(`^[A-Za-z0-9._-]+$`)
	pathRE  = regexp.MustCompile(`^/[A-Za-z0-9._/-]*$`)
	portRE  = regexp.MustCompile(`^(tcp|udp)/[0-9]{1,5}$`)
)

func safeToken(s string) bool { return tokenRE.MatchString(s) }
func safePath(s string) bool  { return pathRE.MatchString(s) }

func validB64(s string, minLen int) bool {
	b, err := base64.StdEncoding.DecodeString(s)
	return err == nil && len(b) >= minLen
}

// Validate rejects values that could break out of the access.conf syntax.
func (s Stanza) Validate() error {
	if len(s.OpenPorts) == 0 {
		return fmt.Errorf("fwknop: stanza without OPEN_PORTS")
	}
	for _, p := range s.OpenPorts {
		if !portRE.MatchString(p) {
			return fmt.Errorf("fwknop: invalid OPEN_PORTS entry %q", p)
		}
	}
	if !validB64(s.KeyBase64, 16) || !validB64(s.HMACKeyBase64, 32) {
		return fmt.Errorf("fwknop: invalid SPA keys")
	}
	if s.HMACDigest != "" && !safeToken(s.HMACDigest) {
		return fmt.Errorf("fwknop: invalid HMAC digest %q", s.HMACDigest)
	}
	if s.AccessTimeout < time.Second {
		return fmt.Errorf("fwknop: access timeout too short")
	}
	if s.ForceNAT != nil {
		if net.ParseIP(s.ForceNAT.IP) == nil || s.ForceNAT.Port <= 0 || s.ForceNAT.Port > 65535 {
			return fmt.Errorf("fwknop: invalid FORCE_NAT %s %d", s.ForceNAT.IP, s.ForceNAT.Port)
		}
	}
	if strings.ContainsAny(s.Comment, "\r\n") {
		return fmt.Errorf("fwknop: comment must be a single line")
	}
	return nil
}

// RenderAccess renders access.conf. fwknopd tries every stanza whose SOURCE
// matches, so each client is told apart by its own keys. SOURCE is ANY but
// REQUIRE_SOURCE_ADDRESS forces the address inside the encrypted SPA packet
// to match the packet source, and the firewall is only opened for it.
func RenderAccess(stanzas []Stanza) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by sdp-services from grants issued by the SDP controller.\n")
	for i, s := range stanzas {
		if err := s.Validate(); err != nil {
			return "", fmt.Errorf("stanza %d: %w", i, err)
		}
		digest := s.HMACDigest
		if digest == "" {
			digest = "SHA256"
		}
		b.WriteString("\n")
		if s.Comment != "" {
			fmt.Fprintf(&b, "# %s\n", s.Comment)
		}
		kv := func(k, v string) { fmt.Fprintf(&b, "%-24s %s\n", k, v) }
		kv("SOURCE", "ANY")
		kv("REQUIRE_SOURCE_ADDRESS", "Y")
		kv("OPEN_PORTS", strings.Join(s.OpenPorts, ", "))
		kv("KEY_BASE64", s.KeyBase64)
		kv("HMAC_KEY_BASE64", s.HMACKeyBase64)
		kv("HMAC_DIGEST_TYPE", strings.ToUpper(digest))
		kv("FW_ACCESS_TIMEOUT", strconv.Itoa(int(s.AccessTimeout/time.Second)))
		if !s.Expires.IsZero() {
			kv("ACCESS_EXPIRE_EPOCH", strconv.FormatInt(s.Expires.Unix(), 10))
		}
		if s.ForceNAT != nil {
			kv("FORCE_NAT", fmt.Sprintf("%s %d", s.ForceNAT.IP, s.ForceNAT.Port))
		}
	}
	return b.String(), nil
}

// ClientStanza is one ~/.fwknoprc stanza.
type ClientStanza struct {
	Name          string
	Server        string
	SPAPort       int
	Access        string // e.g. "tcp/8443"
	AllowIP       string
	KeyBase64     string
	HMACKeyBase64 string
	HMACDigest    string
}

// RenderClientRC renders an fwknop client rc file with a single stanza.
func RenderClientRC(c ClientStanza) (string, error) {
	if !safeToken(c.Name) || !safeToken(c.Server) || !portRE.MatchString(c.Access) ||
		net.ParseIP(c.AllowIP) == nil || !validB64(c.KeyBase64, 16) || !validB64(c.HMACKeyBase64, 32) {
		return "", fmt.Errorf("fwknop: invalid client stanza")
	}
	if c.SPAPort == 0 {
		c.SPAPort = DefaultSPAPort
	}
	digest := c.HMACDigest
	if digest == "" {
		digest = "SHA256"
	}
	if !safeToken(digest) {
		return "", fmt.Errorf("fwknop: invalid HMAC digest")
	}
	var b strings.Builder
	b.WriteString("[default]\n\n")
	fmt.Fprintf(&b, "[%s]\n", c.Name)
	kv := func(k, v string) { fmt.Fprintf(&b, "%-20s %s\n", k, v) }
	kv("SPA_SERVER", c.Server)
	kv("SPA_SERVER_PORT", strconv.Itoa(c.SPAPort))
	kv("SPA_SERVER_PROTO", "udp")
	kv("ACCESS", c.Access)
	kv("ALLOW_IP", c.AllowIP)
	kv("KEY_BASE64", c.KeyBase64)
	kv("HMAC_KEY_BASE64", c.HMACKeyBase64)
	kv("USE_HMAC", "Y")
	kv("HMAC_DIGEST_TYPE", strings.ToUpper(digest))
	return b.String(), nil
}
